from emmy.compiler.pipeline.passes.lowering.tile._fromloop import _stamp_axes, fold_from_loop


def classify(node, free):
    """Run the classification stages over the lifted root tree: the online-softmax pairing first
    (it CONSUMES sibling folds — an expectation channel would otherwise read as a bilinear
    candidate), then the contraction binding on the root's own fold and each operand fold, then
    :func:`_legalize` demotes what downstream cannot consume yet. Needs the output-ordered
    ``free`` axes — role assignment is a whole-kernel fact (the trailing pair is the output's
    ``(m, n)``), which is exactly why this cannot live inside the loop parser."""
    node = pair_softmax(node)
    if len(free) >= 2:
        m_name, n_name = free[-2].name, free[-1].name
        axes = frozenset(a.name for a in free)
        if isinstance(node, Fold) and node.axis is not None:
            r = bind_bilinear(node, m_name, n_name, axes)
            if r is not None:
                con, epi = r
                # A mul-hoist epilogue (the k-invariant factor chain) rides the wrapping
                # projection — the ONE home for a projection.
                node = Fold.projection(body=Body(tuple(epi)), operands=(con,)) if epi else con
        elif isinstance(node, Fold) and node.axis is None and node.operands:
            ops: list = []
            epis: list = []
            changed = False
            for f in node.operands:
                r = bind_bilinear(f, m_name, n_name, axes) if isinstance(f, Fold) and f.axis is not None else None
                if r is None:
                    ops.append(f)
                    continue
                con, epi = r
                ops.append(con)
                epis += list(epi)
                changed = True
            if changed:
                # The rebound channels keep their accumulator names (a hoisted channel's chain
                # DEFINES the original name), so the projection's λ params — bound positionally
                # to the operands' result components — stay consistent with the body's reads.
                node = Fold.projection(body=Body((*epis, *node.body)), operands=tuple(ops))
    return _legalize(node)


def pair_softmax(node):
    """B1 — the online-softmax pairing, stated on ``Fold`` fields: an adjacent operand pair
    ``(rowmax, Σ exp)`` over one axis extent — plus every following EXPECTATION-channel sibling
    that joins it — merges into ONE TWISTED fold, the exp/LSE-family carrier. The pairing
    condition is pure algebra: ``component_ops`` canons ``(maximum,)`` / ``(add,)``, the sum's
    lift result ``exp(score′ − m)`` reading the max's carried state, and the two score cones
    α-equal (:func:`~emmy.compiler.ir.tile.ops._cone_canon` — a composed score is an operand
    EDGE on both folds and compares through its own lowering, so the merged fold carries ONE
    copy). The merged lift holds one score-cone copy + the channels' value cones; the exp weight
    itself is NOT lifted — it is the carrier's own merge, regenerated by the derivation
    (``exp_merge``), which is what makes the pair a change of MONOID, not of program. Channel
    loop-invariant factors commute out of the fold (``Σ c·x = c·Σ x``) and multiply the carried
    state back in the projection body."""
    if not (isinstance(node, Fold) and node.axis is None and len(node.operands) >= 2):
        return node
    ops = list(node.operands)
    epi: list = []
    i = 0
    changed = False
    while i < len(ops) - 1:
        merged = _pair(ops[i], ops[i + 1 :])
        if merged is None:
            i += 1
            continue
        fold, consumed, chan_epi = merged
        ops[i : i + 1 + consumed] = [fold]
        epi += chan_epi
        changed = True
        i += 1
    if not changed:
        return node
    # The channel epilogue APPENDS: an invariant factor may be defined by a body stmt (the
    # held-back reciprocal), and the epilogue's own defs (the rescaled accumulators) are read
    # only by the boundary stores.
    return Fold.projection(body=Body((*node.body, *epi)), operands=tuple(ops))


def _score_cone(f: Fold, res: str) -> list | None:
    """The pure score cone producing ``res`` within fold ``f``'s λ — the backward-cone members
    (body order) restricted to ``Load`` / ``Assign`` / ``Select``, reaching exactly ONE source: a
    ``Load``, or a producer EDGE the step composes (attention's per-key score contraction), which
    leads the returned cone. ``None`` when the value depends on anything else."""
    nodes = {n: e for e in f.operands for n in _operand_result_names(e)}
    if res in nodes:
        return [nodes[res]]  # the bare composed score — the degenerate cone
    cone = Body(f.lift.body).backward_cone([res])
    stmts = list(cone.members)
    if not stmts or any(not isinstance(s, (Load, Assign, Select)) for s in stmts):
        return None
    used = [n for n in nodes if n in {a for s in stmts for a in s.deps()}]
    # A SOURCE is what the cone streams — an INDEXED load or a producer edge. A scalar
    # index-invariant load (a mask fill / eps constant) is a cone member, never a source: the
    # causal-mask spelling carries two of them beside the one streamed score.
    srcs = [s for s in stmts if isinstance(s, Load) and any(e.free_vars() for e in s.index or ())]
    if len(srcs) + len(used) != 1:
        return None
    return [*(nodes[n] for n in used), *stmts]


def _exp_weight(defs: dict, name: str, mx: str) -> str | None:
    """When ``name`` is ``exp(subtract(score′, mx))``, the score′ name — else ``None``."""
    d = defs.get(name)
    sub = defs.get(d.args[0]) if isinstance(d, Assign) and d.op.name == "exp" and len(d.args) == 1 else None
    if isinstance(sub, Assign) and sub.op.name == "subtract" and len(sub.args) == 2 and sub.args[1] == mx:
        return sub.args[0]
    return None


def _components(t: Fold, mx: str, canon: str, states: tuple[str, ...] = ()) -> list[tuple[str, tuple, list, tuple]] | None:
    """Read EVERY additive component of sibling fold ``t`` as a carrier component joining a pair:
    each lifted value factors (``split_invariant_factors``) into loop-invariant factors × the
    pair's own per-element weight (``exp(score′ − mx)``, score′ α-equal to ``canon``) × a residual
    value cone — empty for a DENOMINATOR (the bare weight), non-empty for an EXPECTATION. Loop
    fusion merges the denominator and its expectations into ONE multi-component fold, and the
    pre-fusion spelling keeps them as separate single-component siblings — this reading serves
    both, one component at a time. Returns ``[(state, invariant factors, value-cone stmts, value
    factor names)]`` in component order, or ``None`` — the fold keeps its current reading (every
    component must join; a fold half-in the carrier is not a shape this pairing understands)."""
    o = component_ops(t.combine)
    if o is None or any(x.reduce_canon != "add" for x in o):
        return None
    body = list(t.lift.body)
    # A producer EDGE the fold composes (the score contraction) joins through the weight's score
    # cone (``_score_cone`` reads it as the cone's one source) and is then DROPPED with the rest
    # of the sibling — the merged fold carries the pair's ONE α-equal copy. An edge no component
    # consumes would silently lose compute — decline instead.
    edge_results = {nm for e in t.operands for nm in _operand_result_names(e)}
    if edge_results and not edge_results <= {a for s in body for a in s.deps()}:
        return None
    defs = {n: s for s in body for n in s.defines()}
    out: list[tuple[str, tuple, list, tuple]] = []
    covered: set[int] = set()
    for state, value in zip(t.combine.results, t.lift.results, strict=True):
        if not isinstance(value, str):
            return None
        split = split_invariant_factors(body, value, t.axis.name)
        if split is None:
            return None
        inv, local = split
        # An invariant factor bound through an operand EDGE (the chain form's ``1/den``) is
        # invariant only if that edge is free of the pair's carried states: a projection over
        # the denominator streams the RUNNING denominator once merged, the same defect the
        # sunk-factor case below declines.
        binding = _operand_binding(t)
        banned = {mx, *states}
        for c in inv:
            e = binding.get(c)
            if isinstance(e, Fold) and banned & (set(deep_reads(e.lower())) | deep_defines(e)):
                return None
        weights, values = [], []
        for n in local:
            score = _exp_weight(defs, n, mx)
            if score is not None and (sc := _score_cone(t, score)) is not None and _cone_canon(sc, score, t.axis.name) == canon:
                weights.append(n)
            else:
                values.append(n)
        if len(weights) != 1:
            return None
        vcone = Body(tuple(body)).backward_cone(values)
        stmts = list(vcone.members)
        if any(not isinstance(s, (Load, Assign, Select)) for s in stmts):
            return None
        if ({mx, *states} | set(t.combine.results) | edge_results) & {a for s in stmts for a in s.deps()}:
            # The value cone must be free of the pair's carried states (its own, the max's, and
            # every sibling already joined — a ``1/den`` sunk into the channel's λ would stream
            # against the RUNNING denominator once merged) and of the dropped edges.
            return None
        covered |= {id(s) for s in Body(tuple(body)).backward_cone([value]).members}
        out.append((state, inv, stmts, tuple(values)))
    if any(id(s) not in covered for s in body):
        return None  # an unaccounted stmt feeds no component — not this shape
    return out


def _pair(fmax, rest: list) -> tuple[Fold, int, list] | None:
    """The pair read + the merged TWISTED fold. ``fmax`` must be the bare rowmax; the following
    siblings contribute carrier components (:func:`_components`) — at least one fold, whose FIRST
    component must be the bare denominator (the ``(m, l)`` carrier head every expectation
    rescales against). ``None`` when no pair forms; else ``(merged fold, sibling folds consumed,
    projection epilogue)``."""
    if not (isinstance(fmax, Fold) and fmax.axis is not None and len(fmax.combine.results) == 1):
        return None
    om = component_ops(fmax.combine)
    if om is None or om[0].reduce_canon != "maximum":
        return None
    mx = fmax.out
    score = fmax.lift.results[0]
    if not isinstance(score, str):
        return None
    mcone = _score_cone(fmax, score)
    if mcone is None:
        return None
    if {id(s) for s in fmax.lift.body} - {id(s) for s in mcone}:
        return None  # an unaccounted max-side stmt — not the bare rowmax
    canon = _cone_canon(mcone, score, fmax.axis.name)
    # The merged carrier: ONE score-cone copy (fmax's — the exp weight is the carrier's merge,
    # not the lift), then every joining component's value cone, σ-renamed to the pair axis.
    # Channel invariant factors ride the projection epilogue.
    states = [mx]
    terms: list = [score]
    prefix = list(fmax.lift.body)
    edges = tuple(fmax.operands)
    epilogue: list = []
    consumed = 0
    for t in rest:
        comps = None
        if isinstance(t, Fold) and t.axis is not None and t.axis.extent == fmax.axis.extent:
            comps = _components(t, mx, canon, tuple(states))
        if comps is None:
            break
        ren = {t.axis.name: fmax.axis.name} if t.axis.name != fmax.axis.name else {}
        sig = Sigma({t.axis.name: Var(fmax.axis.name)}) if ren else None
        for state, inv, vstmts, values in comps:
            if ren:
                vstmts = [s.rewrite(lambda n: ren.get(n, n), sig) for s in vstmts]  # noqa: B023
                values = tuple(ren.get(n, n) for n in values)
            prefix += vstmts
            if not values:
                term: str | float = 1.0
            elif len(values) == 1:
                term = values[0]
            else:  # a multi-factor value cone rebuilds its product in the streaming prefix
                term = values[0]
                for k, v in enumerate(values[1:]):
                    nm = f"{state}__v{k}"
                    prefix.append(Assign(name=nm, op="multiply", args=(term, v)))
                    term = nm
            st_name = f"{state}__sum" if inv else state
            states.append(st_name)
            terms.append(term)
            cur = st_name  # the invariant factors multiply the carried sum back (Σ c·x = c·Σ x)
            for k, c in enumerate(inv):
                nm = state if k == len(inv) - 1 else f"{state}__c{k}"
                epilogue.append(Assign(name=nm, op="multiply", args=(cur, c)))
                cur = nm
        consumed += 1
    if consumed == 0 or terms[1] != 1.0:
        return None  # no denominator head — the carrier has nothing to normalize against
    from emmy.compiler.ir.pure.carrier import exp_combine_states  # noqa: PLC0415 — the carrier constructor

    names = tuple(states)
    other = tuple(f"{n}__o" for n in names)
    lift = Lambda(
        params=(fmax.axis.name, *(n for e in edges for n in _operand_result_names(e))),
        body=Body(tuple(prefix)),
        results=(score, *terms[1:]),
    )
    combine = Lambda(params=names + other, body=Body(exp_combine_states(names, other)), results=names)
    merged = Fold(
        axis=fmax.axis,
        unroll=fmax.unroll,
        operands=edges,
        lift=lift,
        # The pivot seeds the max op's IDENTITY (−1e30), never −inf: an ALL-MASKED carrier slice
        # (a coop strided lane, a split-KV chunk) folds only −inf scores, and the rescale
        # ``subtract(m_old, m_new)`` at ``m_old = m_new = −inf`` is NaN — at the finite identity
        # it is 0 and the empty carrier stays (identity, 0, …).
        init=(om[0].identity,) + (0.0,) * (len(names) - 1),
        combine=combine,
    )
    return merged, consumed, epilogue


def _chained_column(col: Fold) -> tuple[Fold, list, Loop] | None:
    """Read a CHAINED column fold — one whose operands carry exactly one zero-axis projection
    edge over one statistic fold — as ``(statistic, epilogue stmts, raw column loop)``: the
    pieces the demoted-loop form of the same cell used to hold apart. ``None`` when ``col`` is
    not that shape."""
    if not isinstance(col, Fold) or col.axis is None:
        return None
    edges = [e for e in col.operands if isinstance(e, Fold) and e.axis is None]
    if len(edges) != 1:
        return None
    (edge,) = edges
    if len(edge.operands) != 1 or not isinstance(edge.operands[0], Fold) or edge.operands[0].axis is None:
        return None
    stat = edge.operands[0]
    if stat.role not in (AxisRole.PLANAR, AxisRole.TWISTED) or stat.composed is not None:
        return None
    bare, _edge = _unchain(col)
    return stat, list(edge.body), bare.loop


def demoted_chain(op):
    """The per-cell READING of a chained root — the chain undone: each chained column fold's
    statistic becomes a root operand, its epilogue and the column's captured loop body members
    (the raw column loop the pre-chain spelling carried), byte-identical at lowering. The reduce
    tiers schedule this view (the statistic's cooperative partition is a ROOT site there); the
    stored chain keeps the nodes — and the seams — the tiers cannot address."""
    if not (isinstance(op, Fold) and op.axis is None):
        return op
    operands: list = []
    body: list = []
    changed = False

    def undo(col: Fold) -> bool:
        """Append ``col``'s pre-chain spelling: its edge's fold operands as root operands (the
        first stays hoisted; the materializer recurses into ``operands[0]`` only, so the rest
        restore to their loops at the body head), the edge body as the epilogue, the column as
        its captured loop."""
        bare, edge = _unchain(col)
        if edge is None:
            return False
        folds = [e for e in edge.operands if isinstance(e, Fold)]
        if folds:
            if not operands:
                operands.append(folds[0])
                rest = folds[1:]
            else:
                rest = folds
            body.extend(s for f in rest for s in f.lower())
        body.extend([*edge.body, bare.loop])
        return True

    for e in op.operands:
        if isinstance(e, Fold) and e.axis is not None and undo(e):
            changed = True
            continue
        operands.append(e)
    for m in op.body:
        if isinstance(m, Fold) and m.axis is not None and undo(m):
            changed = True
        elif isinstance(m, Fold):
            body.extend(m.lower())
            changed = True
        else:
            body.append(m)
    if not changed:
        return op
    return Fold.projection(operands=tuple(operands), body=Body(tuple(body)))


def _split_chain(edge: Fold, a_cone: list, b_cone: list):
    """Partition a chain edge between the two cones that read it: each side takes the backward
    cone (within the edge body) of the edge results it reads, plus the ONE statistic fold those
    stmts read. ``None`` when a side needs two statistics or the sides share one."""
    from emmy.compiler.ir.pure.fold import deep_reads as _dr  # noqa: PLC0415

    results = set(edge.lift.results)
    by_state = {n: e for e in edge.operands if isinstance(e, Fold) for n in (e.combine.results if e.combine is not None else ())}
    out = []
    taken: set[int] = set()
    for cone in (a_cone, b_cone):
        needs = _dr(cone) & results
        members = list(Body(tuple(edge.body)).backward_cone(sorted(needs)).members) if needs else []
        stats = {id(by_state[n]): by_state[n] for s in (*members,) for n in s.deps() if n in by_state}
        stats.update({id(by_state[n]): by_state[n] for n in needs if n in by_state})
        if len(stats) > 1 or any(i in taken for i in stats):
            return None
        taken |= set(stats)
        out.append((next(iter(stats.values()), None), members))
    return out[0], out[1]


def _unchain(col: Fold) -> tuple[Fold, Fold | None]:
    """``col`` with its one zero-axis projection edge detached — the column fold as it read before
    root formation closed it (its λ reading the edge's results as free names) — and that edge."""
    edges = [e for e in col.operands if isinstance(e, Fold) and e.axis is None]
    if len(edges) != 1:
        return col, None
    (edge,) = edges
    bound = set(edge.lift.results)
    bare = replace(
        col,
        operands=tuple(e for e in col.operands if e is not edge),
        lift=Lambda(params=tuple(p for p in col.lift.params if p not in bound), body=col.lift.body, results=col.lift.results),
    )
    return bare, edge


def fused_view(tile) -> tuple[Fold, object, tuple] | None:
    """B3 — the MONOID-PRODUCER composition, read off the lifted tree: a root projection whose one
    operand is a per-row statistic fold (PLANAR Σx² — RMSNorm; TWISTED ``(m, l)`` — softmax·V) and
    whose body is the statistic's scalar epilogue + ONE raw column contraction loop (restored by
    root formation exactly because its cone reads the epilogue), the column axis riding the sweep
    :class:`Store`. That tree ALSO reads as ONE computed-A product contraction: the k-varying cone
    on the ``a`` edge with the statistic as its SOURCE (``make_cone`` — the K seam on the node),
    one :class:`Channel` per ⊗-fold, the column axis joining the grid.

    Returns the same ``(Fold, column Axis, stores)`` the old recognize-time binder returned — or
    ``None`` (not this shape). The returned contraction keeps a wrapping projection only when its
    body has real work; an empty identity projection carries no information. A VIEW, not a rewrite:
    ``classify`` stores the canonical projection tree; this derivation runs on demand at the
    schedule (``_views``) and the golden decode, because which of the two readings a fork row
    realizes is a decision about the SCHEDULE.

    The statistic's OWN composed score binds too (the old ``bound_producer``): a single fold edge
    on the statistic re-binds through :func:`bind_bilinear` — tried against each free axis as the
    row; its columns are the statistic's own axis — so the schedule sees a contraction in both
    places or the statistic stays a scalar sweep while the weight reaches the tensor core."""
    node, free, stores = tile.op, tuple(tile.place.free), tuple(tile.stores)
    if not (isinstance(node, Fold) and node.axis is None):
        return None
    body = list(node.body)
    # The CHAIN form: root formation closed the column fold over the statistic's projected
    # epilogue through a projection edge. It is the root's one operand, or — when it reads the
    # boundary store's sweep axis — the root's one fold body member. The edge's operand is the
    # statistic, its body the epilogue, and the column fold minus that edge regenerates the raw
    # column loop the demoted form carried — byte-identical, so the reading below is unchanged.
    chain = None
    if len(node.operands) == 1:
        chain = _chained_column(node.operands[0])
    elif not node.operands:
        folds = [s for s in body if isinstance(s, Fold)]
        if len(folds) == 1:
            chain = _chained_column(folds[0])
            if chain is not None:
                # Body stmts ahead of the column fold are its prologue (they join the statistic
                # epilogue the cone reads); the rest is the combine tail.
                at = body.index(folds[0])
                chain = (chain[0], [*body[:at], *chain[1]], chain[2])
                body = body[at + 1 :]
    if chain is None and not node.operands and len(stores) == 1 and stores[0].sweep is not None:
        # A chained column over TWO statistics (normalized Q against normalized K): the bilinear
        # binder reads it with the sweep as the column axis and each side's statistic on its cone.
        folds = [s for s in body if isinstance(s, Fold)]
        if len(folds) == 1 and folds[0].axis is not None and free:
            n_ax = stores[0].sweep
            r = bind_bilinear(folds[0], free[-1].name, n_ax.name, frozenset(a.name for a in free) | {n_ax.name})
            if r is not None:
                con, epi = r
                at = body.index(folds[0])
                tail = [*body[:at], *epi, *body[at + 1 :]]
                from emmy.compiler.ir.tile.ir import Store  # noqa: PLC0415

                return Fold.projection(body=Body(tuple(tail)), operands=(con,)), n_ax, (Store(write=stores[0].write),)
    if chain is None:
        if len(node.operands) != 1:
            return None
        stat = node.operands[0]
        if not isinstance(stat, Fold) or stat.axis is None or stat.composed is not None:
            return None
        if stat.role not in (AxisRole.PLANAR, AxisRole.TWISTED):
            return None  # the statistic is a projected reduce; a contraction there is another shape
    if chain is not None and len(stores) == 1 and stores[0].sweep is not None:
        stat, stat_epi, kloop = chain
        n_ax, writes, tail = stores[0].sweep, [stores[0].write], body
    elif chain is not None:
        return None
    elif len(stores) == 1 and stores[0].sweep is not None:
        n_ax, writes = stores[0].sweep, [stores[0].write]
        loops = [i for i, s in enumerate(body) if isinstance(s, Loop) and s.is_reduce]
        if len(loops) != 1:
            return None
        stat_epi, kloop, tail = body[: loops[0]], body[loops[0]], body[loops[0] + 1 :]
    elif not stores and body and isinstance(body[-1], Loop) and not body[-1].is_reduce:
        # The SPLIT PARTIAL's spelling: with one Write per CHANNEL (each fold's raw state to its
        # own workspace slot) and no combine tail, ``split_effects`` declines the sweep, so the
        # column loop stays a raw body member and its writes are the trailing run.
        sweep = body[-1]
        stat_epi = body[:-1]
        inner = list(sweep.body)
        cut = len(inner)
        while cut and isinstance(inner[cut - 1], Write):
            cut -= 1
        writes = inner[cut:]
        if not writes or not inner or not isinstance(inner[0], Loop) or not inner[0].is_reduce:
            return None
        kloop, tail = inner[0], inner[1:cut]
        n_ax = sweep.axis
    else:
        return None
    if not all(w.is_scalar for w in writes):
        return None
    if not all(isinstance(s, (Load, Assign)) for s in stat_epi) or not all(isinstance(s, Assign) for s in tail):
        return None
    if stat.operands:
        if len(stat.operands) != 1 or not isinstance(stat.operands[0], Fold) or stat.operands[0].axis is None:
            return None
        score = _bound_producer(stat.operands[0], free, stat.axis.name)
        if score is None:
            return None  # a composed score the binder cannot read — the base rows stand
        stat = replace(stat, operands=(score,))
    fcol = fold_from_loop(_stamp_axes(kloop))
    if fcol is None:
        return None
    k_name = fcol.axis.name
    # A producer the column fold COMPOSES (attention's per-key score contraction, hoisted to an
    # operand edge by the lift) is stored BOUND where it reads as a contraction, so the schedule
    # sees the bilinear reading (the chained A fill) instead of a scalar fold: rows are one of the
    # kernel's free axes, columns the enclosing contraction's k. An unreadable producer declines
    # the view — the base rows stand.
    edges: list = []
    for e in fcol.operands:
        if not (isinstance(e, Fold) and e.axis is not None):
            return None
        b = _bound_producer(e, free, k_name)
        if b is None:
            return None
        edges.append(b)
    # The statistic prologue must be row-local: its coordinate reads (deep — index exprs, Select
    # predicates) may span (m, its own bound axes) but never the column / contraction axes.
    banned = {n_ax.name, k_name}
    if banned & (_deep_idx_vars([*stat_epi, *stat.lower()]) - stmt_axis_names(stat.lower())):
        return None
    stat_defs = set(_operand_result_names(stat)) | {nm for s in stat_epi for nm in s.defines()}
    edge_names = frozenset(nm for e in edges for nm in _operand_result_names(e))
    bound = _bind_stat_channels(
        fcol, n_ax.name, stat_defs, frozenset(a.name for a in free) | {n_ax.name}, edge_names, m_name=free[-1].name if free else None
    )
    if bound is None:
        return None
    cone, channels = bound
    cone = [*edges, *cone]  # producer nodes join the cone; make_cone hangs them off the operands
    # The combine tail: its reads must be the fold accumulators, its own defs, or STAT-FREE
    # epilogue defs (their cones prepended so the store-side epilogue can re-evaluate them); a
    # stat-DERIVED read would need the reduce's state at the store, which that path has no
    # channel for. The one Write stores the tail's projected scalar (or the bare primary acc).
    derived = set(_operand_result_names(stat))
    for s in stat_epi:
        if set(s.deps()) & derived:
            derived |= set(s.defines())
    accs = {ch.acc for ch in channels}
    tail_defs = {s.name for s in tail}
    prefix_needs = []
    for s in tail:
        for a in s.args:
            if a in accs or a in tail_defs:
                continue
            if a in stat_defs - derived:
                prefix_needs.append(a)
                continue
            return None
    prefix: list = []
    seen: set[int] = set()
    for nm in prefix_needs:
        for st in Body(tuple(stat_epi)).backward_cone([nm]).members:
            if id(st) not in seen:
                seen.add(id(st))
                prefix.append(st)
    # The prefix RE-EVALUATES cone stmts on the store side, so it is a second spelling of their
    # names: α-renamed (``__p``), as the chain formation spells a shared member, so a piece that
    # flattens both sides into one scope (a PLACE cut's parent) never defines a name twice.
    rename = {nm: f"{nm}__p" for st in prefix for nm in st.defines()}
    ren = lambda n: rename.get(n, n)  # noqa: E731
    prefix = [st.rewrite(ren) for st in prefix]
    tail = [st.rewrite(ren) for st in tail]
    # A combine tail projects the channels to ONE value, so it stores once; with no tail every
    # fold's accumulator is stored raw, each exactly once (the split partial's slot-per-channel).
    stored = sorted(tuple(w.values) for w in writes)
    expect = sorted([(tail[-1].name,)] if tail else [(ch.acc,) for ch in channels])
    if stored != expect:
        return None
    con = Fold.contraction(
        k_axis=fcol.axis,
        a=make_cone(cone, k_name, stat=stat, sweep=tuple(stat_epi)),
        channels=channels,
        product=_channel_product(fcol),
        fold_op=component_ops(fcol.combine)[0],
    )
    from emmy.compiler.ir.tile.ir import Store  # noqa: PLC0415

    projection = Body((*prefix, *tail))
    root = Fold.projection(body=projection, operands=(con,)) if projection else con
    return root, n_ax, tuple(Store(write=w) for w in writes)


def _cone_value_key(name: str, defs: dict) -> tuple:
    """The canonical value tree of SSA ``name`` within a λ body — Loads keyed by (buffer, index),
    Assigns by (op, child keys), a name defined outside the body by itself. Two channels share
    one A operand iff their lift values have EQUAL keys (a commutative op's children are sorted,
    so ``x̂·s`` and ``s·x̂`` key equal)."""
    st = defs.get(name)
    if st is None:
        return ("free", name)
    if isinstance(st, Load):
        return ("load", st.input, tuple(e.pretty() for e in st.index))
    if isinstance(st, Select):
        branches = tuple((b.select.pretty() if b.select is not None else "", _cone_value_key(b.value, defs)) for b in st.branches)
        return ("select", branches)
    children = tuple(_cone_value_key(a, defs) for a in st.args)
    if st.op.commutative:
        children = tuple(sorted(children))
    return ("op", st.op.name, children)


def _bound_producer(e: Fold, free: tuple, n_name: str) -> Fold | None:
    """A producer the cone / statistic composes, re-read as a MATERIALIZED-operand contraction —
    or ``None`` when it is not one. Tried against each free axis in turn as the row (its columns
    are the enclosing contraction's ``n_name``); an axis whose bind lands on a COMPUTED operand
    is skipped, not fatal — which axis plays m is a property of the producer's own operand
    indices, and a partition axis the producer never reads can bind spuriously as a broadcast
    cone."""
    axes = frozenset(a.name for a in free) | {n_name, e.axis.name}
    for ax in free:
        if ax.name == n_name:
            continue
        b = bind_bilinear(e, ax.name, n_name, axes, producer=True)
        if b is not None and not b[1] and isinstance(b[0].a, Load) and isinstance(b[0].b, Load):
            return b[0]  # an edge carries no projection epilogue — a hoisted producer declines
    return None


def _channel_product(f: Fold) -> object:
    """The fold's shared ⊗ — the lift stmt op behind its first result (callers run after the
    bilinear read has already verified one shared product)."""
    defs = {s.name: s for s in f.lift.body if isinstance(s, Assign)}
    return defs[f.lift.results[0]].op


def _bind_stat_channels(
    f: Fold, n_name: str, stat_defs: set, axes: frozenset, edge_names: frozenset = frozenset(), m_name: str | None = None
) -> tuple[list, tuple] | None:
    """The computed-A channel read for the fused view: per additive component, a two-arg ⊗
    (distributing over the carrier's one commutative-monoid ⊕) whose directly-named B load is
    ``(n, k)``-indexed, all components sharing ONE A value whose cone reads the statistic —
    every free SSA read of the cone must land in ``stat_defs`` or ``edge_names`` (the results of
    producer edges the fold composes; a stat-FREE cone is the demoted option's shape, not this
    one). Returns ``(cone stmts, channels)`` or ``None``."""
    ops = component_ops(f.combine)
    if ops is None or len(set(ops)) != 1:
        return None
    plus = ops[0]
    if not (plus.associative and plus.commutative and plus.has_identity):
        return None
    k_name = f.axis.name
    body = list(f.lift.body)
    defs = {s.name: s for s in body if isinstance(s, Assign)}
    loads = {s.names[0]: s for s in body if isinstance(s, Load)}
    reads: list[tuple[Assign, Load, str]] = []
    for res in f.lift.results:
        lift = defs.get(res) if isinstance(res, str) else None
        if lift is None or len(lift.args) != 2 or not lift.op.distributes_over(plus):
            return None
        b_arg = next(
            (a for a in lift.args if (ld := loads.get(a)) is not None and {n_name, k_name} <= _idx_vars(ld)),
            None,
        )
        a_arg = next((a for a in lift.args if a != b_arg), None)
        if b_arg is None or a_arg is None:
            return None
        reads.append((lift, loads[b_arg], a_arg))
    if len({lift.op for lift, _, _ in reads}) != 1:
        return None
    if m_name is not None and any(m_name in _idx_vars(b) for _, b, _ in reads):
        # B must be (n, k)-indexed and never read the row axis — the mirror of the A-cone check
        # below. A row-dependent B is a batched matvec, not a bilinear form: the mma emitter
        # addresses ONE B slab per tile, so binding it reads the first row's slab for all 16
        # (decode attention with the heads as rows, V read per head).
        return None
    # ONE shared A value across channels, by VALUE-TREE equality: fusion duplicates the cone SSA
    # per channel (fresh names, interleaved order, per-copy operand order), so name equality is
    # too strict but value-tree equality is exact.
    alldefs = {nm: s for s in body for nm in s.defines()}
    if len({_cone_value_key(a, alldefs) for _, _, a in reads}) != 1:
        return None
    consumed = {id(lift) for lift, _, _ in reads} | {id(b) for _, b, _ in reads}
    stmts = None
    for _, _, a_arg in reads:
        cone = Body(tuple(body)).backward_cone([a_arg])
        members = list(cone.members)
        if not members or any(not isinstance(s, (Load, Assign, Select)) for s in members):
            return None
        ext = set(cone.external_reads) - axes - {k_name} - edge_names
        if not ext or not ext <= stat_defs:
            return None  # a stat-free cone is the demoted option's shape, not ours
        consumed |= {id(s) for s in members}
        if stmts is None:
            stmts = members  # the first copy IS the cone — the others are value-equal duplicates
    if any(isinstance(s, Load) and n_name in _idx_vars(s) for s in stmts):
        return None  # the cone must be (m, k)-indexed — an n-dependent producer isn't the A tile
    # The cone must be K-VARYING: a member load indexed by k, or a read of a composed producer
    # edge (attention's per-key score — the K variance is the edge's, not a member load's).
    if not any(isinstance(s, Load) and k_name in _idx_vars(s) for s in stmts) and not ({a for s in stmts for a in s.deps()} & edge_names):
        return None
    if any(id(s) not in consumed for s in body):
        return None  # an unaccounted λ stmt — a shape this binding does not understand
    if len({k_name in b.index[-1].free_vars() for _, b, _ in reads}) != 1:
        return None  # B-layout agreement: one shared A fragment, one slab orientation
    return stmts, tuple(Channel(b=b, acc=acc) for (_, b, _), acc in zip(reads, f.combine.results, strict=True))


def _legalize(node):
    """Demote what a NAMED downstream capability cannot consume — an explicit list that shrinks
    as stages land, never a parity list. Two entries today:

    - **multi-operand root projections** — materialization stamps ONE root site tree
      (``_schedule._materialize``) and the materializer recurses into ``operands[0]`` only, so
      the first operand stays hoisted and the rest are restored to their verbatim loops at the
      body head, in order. Scope holds by construction: a restored loop may read the kept
      operand's carried state (operands lower first), never the reverse — hoisting required
      reading nothing the body defines. The online-softmax pairing consumes the sibling pair
      into one TWISTED fold ahead of this demotion.
    - **a Fold nested inside a RAW body stmt** — a term below a non-Fold stmt is not a stored
      form (the structural key and the scalar render walk stmts, not terms), reached when
      ``split_effects`` declines a sweep whose members the lift had typed. The member lowers
      back to its verbatim loop (the parser's gate makes that byte-exact); the fused reading of
      that sweep is :func:`fused_view`'s to re-derive.

    A raw REDUCE loop restored beside a hoisted fold needs no entry here: the cooperative
    emitter runs it serially per lane (``_factor._tile_reduce_axis`` — lane striding is for
    FREE sweeps only), so the restored sibling stays correct on every tier."""
    if isinstance(node, Fold) and node.axis is None and len(node.operands) > 1:
        keep, rest = node.operands[0], node.operands[1:]
        node = Fold.projection(body=Body((*(s for f in rest for s in f.lower()), *node.body)), operands=(keep,))
    if isinstance(node, Fold) and node.axis is None and any(isinstance(s, Loop) for s in node.body):
        lowered = tuple(_lower_nested_folds(s) if isinstance(s, Loop) else s for s in node.body)
        if any(a is not b for a, b in zip(lowered, node.body, strict=True)):
            node = replace(node, lift=_replace_body(node.lift, Body(lowered)))
    return node


def _lower_nested_folds(s: Loop) -> Loop:
    """``s`` with every ``Fold`` member below it lowered to its verbatim loop, deep."""
    members: list = []
    changed = False
    for m in s.body:
        if isinstance(m, Fold):
            members.extend(m.lower())
            changed = True
        elif isinstance(m, Loop):
            lowered = _lower_nested_folds(m)
            changed = changed or lowered is not m
            members.append(lowered)
        else:
            members.append(m)
    return s if not changed else replace(s, body=Body(tuple(members)))


def _replace_body(lift: Lambda, body: Body) -> Lambda:
    """``lift`` with ``body`` swapped in — through the raw-loop-IR formation arm (the escape
    body is impure by definition)."""
    from emmy.compiler.ir.pure.fold import _loop_ir_fn  # noqa: PLC0415

    return _loop_ir_fn(lift.params, body, lift.results)


def _idx_vars(load: Load) -> set[str]:
    """Every free Var name across a load's index exprs."""
    return {v for e in load.index or () for v in e.free_vars()}


def _role_pure(load: Load, on: str, axes: frozenset) -> bool:
    """Per-expr role purity: every index expr of ``load`` that mentions the role axis ``on``
    mentions no OTHER free (grid) axis. The mma emitters address an operand slab by its role
    axis and the reduce axis alone — a third grid axis in a *separate* dim is a batch offset
    the grid absorbs, but one composed into the SAME expr as the role axis (a split-axis
    composite index) has no slab address, and binding it emits code that references an
    undefined iteration var. Checking here turns that miscompile into a decline."""
    others = axes - {on}
    return not any(e.free_vars() & others for e in load.index or () if on in e.free_vars())


def _deep_idx_vars(stmts) -> set[str]:
    """Every free Var name across the coordinate exprs reachable in ``stmts`` (deep) — index
    exprs and ``Select`` predicates alike (``Stmt.exprs``)."""
    out: set[str] = set()
    for s in stmts:
        out |= {v for e in s.exprs() for v in e.free_vars()}
        for b in s.nested():
            out |= _deep_idx_vars(list(b))
    return out


def _cone(body: list, arg: str, avoid_name: str, k_name: str, axes: frozenset, bound: frozenset = frozenset()) -> list | None:
    """The backward cone of ``arg`` within a λ body, when it reads as a pure MAP producer for one
    contraction side: every member a ``Load`` / ``Assign`` / ``Select``, self-contained (no free
    SSA reads — a cross-operand read is another stage's shape; an AXIS var is an iteration
    coordinate, not a read), no member load indexed by the OTHER side's grid axis, and at least
    one K-indexed load (a k-invariant value is a hoistable factor, not an operand). ``None`` when
    the cone is not this shape."""
    cone = Body(tuple(body)).backward_cone([arg])
    stmts = list(cone.members)
    if not stmts or any(not isinstance(s, (Load, Assign, Select)) for s in stmts):
        return None
    if set(cone.external_reads) - axes - {k_name} - bound:
        return None
    loads = [s for s in stmts if isinstance(s, Load)]
    if any(avoid_name in _idx_vars(ld) for ld in loads) or not any(k_name in _idx_vars(ld) for ld in loads):
        return None
    return stmts


def bind_bilinear(f: Fold, m_name: str, n_name: str, axes: frozenset = frozenset(), producer: bool = False) -> tuple[Fold, tuple] | None:
    """Rebind a lifted fold as the bilinear contraction — the ONE contraction reading, off the λ
    spelling and stated on the ALGEBRAIC TRAITS, never op names: the carrier must be a product of
    ONE commutative-monoid ⊕ (associative + commutative + identity — the reassociation license
    split-K and the tree/atomic combines rely on), and each ``lift.results[i]`` must name a
    two-arg ⊗ — one shared op across channels — with ``⊗.distributes_over(⊕)`` (the
    registered-semiring table; ``(multiply, add)`` is the matmul). The ⊗ args classify by their
    loads' grid-axis indexing — B is the ``(n, k)``-indexed side and never reads ``m``, A the
    mirror (role-exclusive: a load carrying both axes is neither, and the fold stays PLANAR).
    Role purity is per index EXPR (:func:`_role_pure`): another free axis may ride a separate
    dim (a batch offset), never the same expr as the role axis — the DIRECT slab loaders
    template an operand address over the bare role Var and cannot spell a composite, so it
    declines instead of reaching an emitter that miscompiles it. ``producer=True``
    (:func:`_bound_producer` — a composed edge the chained A fill consumes) waives the check:
    the fill σ-substitutes whole index exprs, and the split-KV reindex legitimately spells the
    absolute key as ``ordinal·B + local`` in one expr.
    One side may be a pure MAP cone (the computed operand: A rides :func:`make_cone`, which
    fixes the K seam on the node; B a plain projection evaluated per slab cell). N channels must
    share ONE A value — sharing is the node's arity. Every λ body stmt must be consumed by a
    lift or a cone (:meth:`Fold.contraction` REGENERATES the lift, so an unaccounted stmt would
    be silently dropped — decline instead). ``None`` when any condition fails; the caller keeps
    the PLANAR fold unchanged.

    Deliberately not yet bound here: the both-computed decode pair and the k-invariant factor
    hoist (the fp8 / W8A8 mul-hoist arm — the ``Σ a⊗(s⊗w) = s⊗Σ a⊗w`` reassociation, licensed
    by the same distributivity/commutativity traits) — registered casualties until ported to
    the λ body."""
    if f.axis is None or f.combine is None:
        return None
    stat = sweep = None
    edge = None
    bound_values: frozenset = frozenset()
    if f.operands:
        # The CHAIN form: root formation closed this fold over the values it reads through one
        # projection edge (a statistic's projected epilogue, or two of them — one per side).
        # Bind the bare fold and hang each side's statistic + epilogue on that side's cone as
        # its source (``make_cone(stat=…)``) — the reading the demoted-loop form reached only
        # through ``fused_view``.
        chain = _chained_column(f)  # one statistic: its cone source; two: split per side below
        bare, edge = _unchain(f)
        if edge is None or any(isinstance(e, Fold) and e.axis is None for e in bare.operands):
            return None  # a fold composing other producers — another stage's shape
        f = bare
        bound_values = frozenset(edge.lift.results)  # the edge's results — row-invariant values the cones may read
        if chain is not None:
            stat, sweep, _ = chain
    ops = component_ops(f.combine)
    if ops is None or len(set(ops)) != 1:
        return None  # the carrier is not a product of ONE ⊕ monoid
    plus = ops[0]
    if not (plus.associative and plus.commutative and plus.has_identity):
        return None  # the reassociation license — the traits every contraction tier relies on
    k_name = f.axis.name
    body = list(f.lift.body)
    defs = {s.name: s for s in body if isinstance(s, Assign)}
    loads = {s.names[0]: s for s in body if isinstance(s, Load)}

    def role_load(name: str, on: str, off: str) -> Load | None:
        ld = loads.get(name)
        if ld is None or on not in _idx_vars(ld) or off in _idx_vars(ld):
            return None
        return ld if producer or _role_pure(ld, on, axes) else None

    # The per-channel ⊗ reads: each result's two-arg multiply, its directly-named B load (or
    # ``None`` when B rides a computed value), and the other argument — the channel's A value.
    reads: list[tuple[Assign, Load | None, str]] = []
    for res in f.lift.results:
        lift = defs.get(res) if isinstance(res, str) else None
        if lift is None or len(lift.args) != 2 or not lift.op.distributes_over(plus):
            return None  # the lift is not a ⊗ of the carrier's semiring — the fold keeps its reduce reading
        if lift.args[0] == lift.args[1]:
            return None  # a square product (both args one value — Σ x·x) has no role split
        b_arg = next((a for a in lift.args if role_load(a, n_name, m_name) is not None), None)
        a_arg = next(a for a in lift.args if a != b_arg)
        reads.append((lift, loads.get(b_arg) if b_arg is not None else None, a_arg))
    if len({lift.op for lift, _, _ in reads}) != 1:
        return None  # the channels must share ONE ⊗ — a mixed-product body is not a bilinear form
    if len({a for _, _, a in reads}) != 1:
        return None  # channels do not share ONE A value — not the product-carrier shape
    a_arg = reads[0][2]
    consumed: set[int] = {id(lift) for lift, _, _ in reads}

    def role_leaf(on: str, off: str) -> Load | None:
        # The role-EXCLUSIVE K-indexed leaf over the WHOLE λ body — the raw storage-dtype load a
        # decode cone wraps is not named by the ⊗ lift, so it is found positionally, as the old
        # binder found it.
        return next(
            (
                s
                for s in body
                if isinstance(s, Load)
                and k_name in _idx_vars(s)
                and on in _idx_vars(s)
                and off not in _idx_vars(s)
                and (producer or _role_pure(s, on, axes))
            ),
            None,
        )

    def hoisted() -> tuple[Fold, tuple] | None:
        # The mul-hoist arm (fp8 / W8A8, either side or BOTH): a storage decode × k-invariant
        # multiplicative factors — the factors commute out of the fold (``Σ a⊗(s⊗w) = s⊗Σ a⊗w``,
        # the same reassociation category as split-K) onto the renamed accumulator in the
        # projection epilogue, and the decode is ABSORBED by the load's own storage dtype.
        if len(reads) != 1:
            return None
        h = _hoist_factors(body, reads[0][0], role_leaf(m_name, n_name), role_leaf(n_name, m_name), k_name, f.combine.results[0])
        if h is None:
            return None
        a_l, b_l, raw, chain = h
        con = Fold.contraction(k_axis=f.axis, a=a_l, channels=(Channel(b=b_l, acc=raw),), product=reads[0][0].op, fold_op=plus)
        return con, tuple(chain)

    if all(b is not None for _, b, _ in reads):
        consumed.update(id(b) for _, b, _ in reads)
        a_edge = role_load(a_arg, m_name, n_name)
        if a_edge is not None and stat is not None:
            return None  # a materialized A beside a chained statistic is not the computed-A shape
        if a_edge is not None:
            if len(reads) > 1:
                # A multi-channel node over a MATERIALIZED shared A (the merged QKV cell) has no
                # consumer tier yet: cp.async / TMA staging is single-fold, and only the smem
                # compute fill (a COMPUTED A) rides multi-channel. The fold keeps its PLANAR
                # reading — exactly the old single-Accum candidacy's behavior.
                return None
            consumed.add(id(a_edge))
        else:
            h = hoisted()
            if h is not None:
                return h
            cone = _cone([s for s in body if id(s) not in consumed], a_arg, n_name, k_name, axes, bound_values)
            if cone is None:
                return None  # a computed A that does not read cleanly — the fold stays PLANAR
            consumed.update(id(s) for s in cone)
            a_edge = make_cone(cone, k_name, stat=stat, sweep=tuple(sweep)) if stat is not None else make_cone(cone, k_name)
        b_edges: list = [b for _, b, _ in reads]
    elif stat is None and len(reads) == 1 and (a_edge := role_load(a_arg, m_name, n_name)) is not None:
        # B rides a computed value (A is the direct load). A storage decode × k-invariant factors
        # binds through the mul-hoist first; any other pure MAP cone is a closed zero-axis
        # operand node — no row-statistic seam to split; its whole MAP tree is evaluated at each
        # (k, n) slab cell.
        h = hoisted()
        if h is not None:
            return h
        consumed.add(id(a_edge))
        lift = reads[0][0]
        b_arg = next(a for a in lift.args if a != a_arg)
        cone = _cone([s for s in body if id(s) not in consumed], b_arg, m_name, k_name, axes)
        if cone is None:
            return None
        consumed.update(id(s) for s in cone)
        b_edges = [Fold.projection(body=Body(tuple(cone)))]
    elif edge is not None and len(reads) == 1:
        # Both sides computed over a chained edge — attention's normalized Q and normalized K,
        # each side's cone reading its own statistic's projected scale. Each cone hangs its
        # statistic + epilogue as its source; the fill evaluates a computed B per slab cell,
        # and the ``b`` seam is the cut that materializes the normalized keys.
        h = hoisted()
        if h is not None:
            return h
        lift = reads[0][0]
        other = next(a for a in lift.args if a != a_arg)
        # Which ⊗ argument is the row side is a property of the cones' indices, not of the
        # argument order: try the lift's order, then the swap.
        rest = [s for s in body if id(s) not in consumed]
        a_cone = b_cone = None
        for a_try, b_try in ((a_arg, other), (other, a_arg)):
            a_cone = _cone(rest, a_try, n_name, k_name, axes, bound_values)
            b_cone = _cone(rest, b_try, m_name, k_name, axes, bound_values)
            if a_cone is not None and b_cone is not None:
                break
        if a_cone is None or b_cone is None:
            return None
        split = _split_chain(edge, a_cone, b_cone)
        if split is None:
            return None
        (a_stat, a_epi), (b_stat, b_epi) = split
        consumed.update(id(s) for s in a_cone)
        consumed.update(id(s) for s in b_cone)
        a_edge = make_cone(a_cone, k_name, stat=a_stat, sweep=tuple(a_epi))
        b_edges = [make_cone(b_cone, k_name, stat=b_stat, sweep=tuple(b_epi))]
    else:
        # Both sides computed with no chain — the W8A8 double-decode pair binds through the
        # mul-hoist alone.
        return hoisted()
    if any(id(s) not in consumed for s in body):
        return None  # an unaccounted λ stmt — a shape this binding does not understand
    # B-layout agreement across channels: one shared A fragment implies one slab orientation
    # (k-last vs k-first), so disagreeing loads never group.
    if len({k_name in b.index[-1].free_vars() if isinstance(b, Load) else True for b in b_edges}) != 1:
        return None
    con = Fold.contraction(
        k_axis=f.axis,
        a=a_edge,
        channels=tuple(Channel(b=b, acc=acc) for b, acc in zip(b_edges, f.combine.results, strict=True)),
        product=reads[0][0].op,
        fold_op=plus,
    )
    return con, ()


def _hoist_factors(body: list, lift: Assign, a_leaf: Load | None, b_leaf: Load | None, k_name: str, acc: str) -> tuple | None:
    """Bind a computed operand (either side — or BOTH, the W8A8 shape) whose cone is a storage
    decode times k-invariant multiplicative factors — the mul-hoist, ported to the λ body. Each
    lift argument must be the operand ``Load`` itself, or factor as ``(storage decode of that
    side's leaf) ⊗ k-invariant factors`` where ⊗ is a multiply / divide chain: a factor CONSTANT
    along the reduce axis commutes out of the fold, so the factors move onto the accumulator in
    the projection EPILOGUE, and the decode is ABSORBED by the load's own storage dtype. The
    chain's leaf is recognized by TRAIT (``ElementwiseImpl.decodes``), never by op name; a
    k-varying (2-D block) scale does not commute and the arm declines.

    Returns ``(a_leaf, b_leaf, raw_acc, chain)`` — the accumulator renamed to ``<acc>__mh`` so
    the epilogue's factor chain can DEFINE ``acc`` and every downstream reader sees the scaled
    value — or ``None`` (not this shape)."""
    if a_leaf is None or b_leaf is None:
        return None
    defs = {s.name: s for s in body if isinstance(s, Assign)}

    def cone(name: str) -> list | None:
        members = list(Body(tuple(body)).backward_cone([name]).members)
        return members if members and all(isinstance(s, (Load, Assign, Select)) for s in members) else None

    def cone_names(name: str) -> set[str] | None:
        c = cone(name)
        return None if c is None else {n for s in c for n in s.defines()}

    def k_free(name: str) -> bool:
        c = cone(name)
        return c is not None and not any(refs_axis(s, k_name) for s in c)

    factors: list[tuple[str, str]] = []  # (op, ssa) applied to the accumulator, outer chain first
    for arg in lift.args:
        if arg in (a_leaf.names[0], b_leaf.names[0]):
            continue  # a directly-named operand — nothing to decode or hoist on this side
        names = cone_names(arg)
        if names is None:
            return None
        in_a, in_b = a_leaf.names[0] in names, b_leaf.names[0] in names
        if in_a == in_b:
            return None  # both leaves in one cone / neither — not the decode-times-factors chain
        leaf = a_leaf if in_a else b_leaf
        bits = leaf.names[0]
        cur = arg
        while True:
            st = defs.get(cur)
            if st is None:
                return None
            if st.op.name in ("multiply", "divide") and len(st.args) == 2:
                x, y = st.args
                xs, ys = cone_names(x), cone_names(y)
                if xs is None or ys is None or (bits in xs) == (bits in ys):
                    return None  # the operand on both sides / neither — not the decode-times-factors chain
                w_side, s_side = (x, y) if bits in xs else (y, x)
                if st.op.name == "divide" and bits not in xs:
                    return None  # ``s / w`` — the divide does not commute out of the fold
                if not k_free(s_side):
                    return None  # a k-varying factor (2-D block scale) stays in the fold — decline
                factors.append((st.op.name, s_side))
                cur = w_side
                continue
            storage = st.op.decodes
            if storage is not None and st.args == (bits,) and (leaf.dtype is None or leaf.dtype.name == storage):
                # The chain's leaf IS the registered decode for the load's storage dtype.
                break
            return None
    # Full coverage: every λ stmt is the lift, an operand leaf, or a member of a bound cone.
    bound = {id(s) for s in cone(lift.args[0]) or ()} | {id(s) for s in cone(lift.args[1]) or ()}
    if any(isinstance(s, (Load, Assign)) and id(s) not in bound and s is not lift for s in body):
        return None
    if not factors:  # bare decode(s) — the operands bind as the raw storage-dtype loads, nothing to hoist
        return a_leaf, b_leaf, acc, ()
    hoisted_stmts: list = []
    seen: set[int] = set()
    for _opn, nm in factors:
        for st in cone(nm) or ():
            if id(st) not in seen:
                seen.add(id(st))
                hoisted_stmts.append(st)
    raw = f"{acc}__mh"
    chain: list = []
    cur_val = raw
    for i, (opn, nm) in enumerate(factors):
        out_nm = acc if i == len(factors) - 1 else f"{raw}{i}"
        chain.append(Assign(name=out_nm, op=opn, args=(cur_val, nm)))
        cur_val = out_nm
    return a_leaf, b_leaf, raw, (*hoisted_stmts, *chain)
